// kernel32/gui.h - MangoWin graphical interface: shared definitions.
// Module layout (see docs/graphics-design.md):
//   gui.c        main loop, enter/exit (owns the event loop)
//   gui_draw.c   backbuffer primitives, cursor cache, full scene render
//   gui_win.c    window + control (button) model, drawing, actions
//   gui_input.c  mouse interaction state machine (click / drag)
//   gui_cmd.c    serial command injection
//   gui_stats.c  PIT timing + performance statistics (owns no hardware:
//                PIT ch0 is borrowed from / returned to timer.c)
#ifndef MANGO_GUI_H
#define MANGO_GUI_H

#define GUI_W          800
#define GUI_H          600
#define GUI_MAX_WIN    8
#define GUI_TITLE_H    16
#define GUI_CLOSE      16
#define GUI_CAPTION    20
#define GUI_MAX_CTL    4
#define CTL_LABEL      16

#define GUI_TASKBAR_H  32              /* system layer at the bottom */
#define GUI_MAX_ICON   8               /* desktop icon slots */
#define GUI_ICON_SIZE  32              /* icon bitmap width/height */

#define GUI_BACK       ((unsigned int *)0x100000)

#define C_BG           0x14161Eu
#define C_BORDER       0xCFCFCFu
#define C_TITLE        0x1F3FBFu
#define C_TITLE_INA    0x4A5A80u        /* inactive window title */
#define C_WINBG        0x2A2F3Au
#define C_CLOSEBG      0xB02020u
#define C_CLOSEFG      0xFFFFFFu
#define C_TEXT         0xFFFFFFu
#define C_CURSOR       0xE0E0E0u
#define C_BTN          0x9A9A9Au
#define C_BTN_EDGE     0x555555u
#define C_BTN_PRS      0x6A6A6Au
#define C_BTN_TEXT     0x000000u

#define C_TASKBAR      0x1E222Cu        /* taskbar background */
#define C_TB_BTN       0x3A4150u        /* taskbar button face */
#define C_TB_ACT       0x1F3FBFu        /* active window button */
#define C_TB_MIN       0x232733u        /* minimized window button */
#define C_MENU_BG      0x1E222Cu        /* start menu background */
#define C_TEXT_INA     0x7A8290u        /* disabled (placeholder) text */

/* button actions */
#define CTL_ACT_PRINT  0
#define CTL_ACT_CLOSE  1

/* control types */
#define CTL_TYPE_BUTTON  0
#define CTL_TYPE_LABEL   1

typedef struct {
    int x, y, w, h;              /* position inside the window content area */
    char label[CTL_LABEL];
    unsigned char type;          /* CTL_TYPE_* */
    unsigned char act;           /* CTL_ACT_* (buttons) */
} gui_ctl_t;

typedef struct {
    int x, y, w, h;              /* window rectangle (pixels) */
    char title[GUI_CAPTION];
    int alive;
    int visible;                 /* 0 while minimized */
    gui_ctl_t ctl[GUI_MAX_CTL];  /* button controls */
} gui_win_t;

/* desktop icon: 32x32 bitmap (0 = transparent), caption, action */
typedef struct {
    const unsigned int *img;     /* GUI_ICON_SIZE x GUI_ICON_SIZE RGBA */
    char name[12];
    void (*act)(int self);       /* self = icon index */
    int win;                     /* window owned by this icon, -1 = none */
} gui_icon_t;

/* shared state (defined in gui.c / gui_win.c) */
extern unsigned int *back;
extern gui_win_t wins[GUI_MAX_WIN];
extern gui_icon_t gui_icons[GUI_MAX_ICON];
extern int active_win;           /* topmost active window, -1 = none */
extern int zorder[GUI_MAX_WIN];  /* paint/hit order, last = top */
extern int zorder_n;             /* number of live windows */
extern volatile int gui_quit;
extern int gui_dirty;

/* 32x32 GUI_ICON_SIZE bitmaps, 0x00RRGGBB with 0 = transparent.
   GENERATED by tools/png_to_c.py from the PNGs in assets/ - do not edit. */
extern const unsigned int icon_computer[GUI_ICON_SIZE * GUI_ICON_SIZE];
extern const unsigned int icon_explorer[GUI_ICON_SIZE * GUI_ICON_SIZE];
extern const unsigned int icon_recycle[GUI_ICON_SIZE * GUI_ICON_SIZE];
extern const unsigned int icon_settings[GUI_ICON_SIZE * GUI_ICON_SIZE];
extern const unsigned int icon_start[GUI_ICON_SIZE * GUI_ICON_SIZE];
extern int press_win, press_ctl;   /* control currently pressed (for faces) */

/* gui_draw.c */
void gui_flip(void);
void gui_render_all(void);
void gui_cursor_reset(void);
void gui_cursor_erase(void);
void gui_cursor_draw(int x, int y);
int cursor_old_x(void);
int cursor_old_y(void);
void bpx(int x, int y, unsigned int c);
void brect(int x, int y, int w, int h, unsigned int c);
void bframe(int x, int y, int w, int h, unsigned int c);
void bchar(int x, int y, unsigned char ch, unsigned int fg,
           unsigned int bg);
void btext(int x, int y, const char *s, unsigned int fg,
           unsigned int bg);

/* gui_win.c */
int gui_win_create(int x, int y, int w, int h, const char *title);
int gui_ctl_add(int win, int x, int y, int w, int h, const char *label,
                int act);
int gui_ctl_label(int win, int x, int y, const char *text);
int win_inside_close(const gui_win_t *w, int x, int y);
void gui_draw_win(const gui_win_t *w, int win_idx);
void gui_ctl_trigger(gui_win_t *w, const gui_ctl_t *b);
void gui_win_activate(int idx);   /* raise to top + mark active */
void gui_win_minimize(int idx);   /* hide; activate next visible window */
void gui_win_restore(int idx);    /* show again + activate */
void gui_win_close(int idx);      /* destroy + unlink icon + fix zorder */

/* gui_taskbar.c */
void gui_taskbar_draw(void);
int gui_taskbar_hit(int mx, int my);   /* -2 = start button, else window idx */
void gui_taskbar_click(int idx);       /* activate / minimize toggle */
void gui_taskbar_tick(void);           /* per-frame: refresh the clock */
void gui_icons_draw(void);
int gui_icon_hit(int mx, int my);      /* icon index under the cursor */
void gui_icon_click(int idx);
void gui_icon_unlink(int win_idx);     /* forget a closed window */
void gui_icon_init(void);
void gui_start_menu_toggle(void);
void gui_start_menu_close(void);
void gui_start_menu_draw(void);
int gui_start_menu_hit(int mx, int my);
void gui_start_menu_click(int idx);
int gui_start_menu_is_open(void);

/* gui.c */
void gui_open_mango(void);             /* window factories (menu/icons) */
void gui_open_computer(void);

/* gui_input.c */
void gui_input_process(int btn_down, int moved, int mx, int my);
void gui_input_reset(void);

/* gui_cmd.c */
void gui_serial_poll(void);

/* gui_stats.c - all PIT access goes through timer.h */
void stats_init(void);
void stats_shutdown(void);
void stats_tick(void);
void stat_render_add(unsigned long du);
void stat_cursor_add(unsigned long du);

/* gui.c */
void gui_enter(void);
void gui_exit(void);

#endif /* MANGO_GUI_H */
