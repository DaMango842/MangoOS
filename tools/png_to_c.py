#!/usr/bin/env python3
"""tools/png_to_c.py - convert the RGBA PNG icons from the assets/
resource directory into a C source file with 32x32 colour arrays.

Pixels are blended onto the desktop background colour (C_BG), then
emitted as 0xRRGGBB values.  One array per PNG, named icon_<stem>.

Offline tool: the generated kernel32/gui_icons.c is committed, so the
kernel build has no dependency on this script or on PIL.
"""

import os
import re
import sys

SIZE = 32
BG = (0x14, 0x16, 0x1E)      # C_BG desktop colour


def blend(r, g, b, a):
    if a <= 0:
        return (0, 0, 0)        # fully transparent: 0 in the C array
    f = a / 255.0
    return (int(r * f + BG[0] * (1 - f)),
            int(g * f + BG[1] * (1 - f)),
            int(b * f + BG[2] * (1 - f)))


def main():
    from PIL import Image

    assets = os.path.normpath(os.path.join(os.path.dirname(__file__),
                                           "..", "assets"))
    names = sys.argv[1:] or sorted(f for f in os.listdir(assets)
                                   if f.endswith(".png"))
    if not names:
        print("no PNG icons in", assets)
        return 1

    out_path = os.path.normpath(os.path.join(os.path.dirname(__file__),
                                             "..", "kernel32",
                                             "gui_icons.c"))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// generated by tools/png_to_c.py from assets/ - do not edit\n")
        for name in names:
            stem = os.path.splitext(name)[0]
            arr = "icon_" + re.sub(r"[^A-Za-z0-9_]", "_", stem)
            img = Image.open(os.path.join(assets, name)).convert("RGBA")
            if img.size != (SIZE, SIZE):
                print("warning:", name, "not 32x32, resizing")
                img = img.resize((SIZE, SIZE), Image.LANCZOS)
            f.write("const unsigned int %s[32 * 32] = {\n" % arr)
            for y in range(SIZE):
                row = []
                for x in range(SIZE):
                    r, g, b, a = img.getpixel((x, y))
                    br, bg, bb = blend(r, g, b, a)
                    row.append("0x%02X%02X%02X" % (br, bg, bb))
                f.write("    " + ", ".join(row) +
                        ("," if y < SIZE - 1 else "") + "\n")
            f.write("};\n")
    print("wrote", out_path)


if __name__ == "__main__":
    sys.exit(main())