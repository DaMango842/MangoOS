#!/usr/bin/env python3
# tools/fc/rom2c.py - turn a user-provided .nes file into kernel32/fc/fc_rom.c
#
# Copyright: the ROM image is the user's property and is NOT part of the
# MangoOS source tree (roms/ is git-ignored). fc_rom.c is generated at
# build time from roms/ and must not be committed.
#
# iNES header: 16 bytes (magic 'NES'+0x1A, prg16, chr8, flags6, flags7,
# then padding). We keep the raw header in rom_data[] so the emulator can
# parse mapper/mirroring at runtime.
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__)) + "/../.."


def find_nes(rom_dir, want):
    if want:
        for name in sorted(os.listdir(rom_dir)):
            if name.lower() == want.lower():
                return os.path.join(rom_dir, name)
        for name in sorted(os.listdir(rom_dir)):
            if want.lower() in name.lower() and name.lower().endswith(".nes"):
                return os.path.join(rom_dir, name)
        print("requested ROM not found in roms/:", want)
        sys.exit(1)
    for name in sorted(os.listdir(rom_dir)):
        if name.lower().endswith(".nes"):
            return os.path.join(rom_dir, name)
    return None


def main():
    rom_dir = os.path.join(ROOT, "roms")
    want = os.environ.get("ROM_NAME", "")
    if len(sys.argv) > 1:
        want = sys.argv[1]
    nes = find_nes(rom_dir, want)
    if nes is None:
        print("no .nes file found in roms/ (user-provided, git-ignored)")
        sys.exit(1)

    data = open(nes, "rb").read()
    if len(data) < 16 or data[0:4] != b"NES\x1a":
        print("bad iNES file:", nes)
        sys.exit(1)
    prg16 = data[4]
    chr8 = data[5]
    expect = 16 + prg16 * 16384 + chr8 * 8192
    if len(data) != expect:
        print("size mismatch: %d != %d" % (len(data), expect))
        sys.exit(1)

    out = os.path.join(ROOT, "kernel32", "fc", "fc_rom.c")
    lines = []
    lines.append("// kernel32/fc/fc_rom.c - GENERATED by tools/fc/rom2c.py, do not edit.\n")
    lines.append("// Embeds the user-provided iNES ROM (git-ignored, not\n")
    lines.append("// redistributed). Source: %s\n" % os.path.basename(nes))
    lines.append("#include \"fc.h\"\n\n")
    lines.append("const unsigned char fc_rom_data[%d] = {\n" % len(data))
    for i in range(0, len(data), 12):
        row = ", ".join("0x%02x" % b for b in data[i : i + 12])
        lines.append("    %s,\n" % row)
    lines.append("};\n")
    lines.append("const int fc_rom_size = %d;\n" % len(data))
    gen = "".join(lines).encode("utf-8")
    if os.path.exists(out) and open(out, "rb").read() == gen:
        print("unchanged %s (%d bytes from %s)"
              % (out, len(data), os.path.basename(nes)))
        return
    with open(out, "wb") as f:
        f.write(gen)
    print("wrote %s (%d bytes from %s)" % (out, len(data), os.path.basename(nes)))


if __name__ == "__main__":
    main()
